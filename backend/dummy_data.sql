-- Summary
SELECT 
    'Desks Created' AS Summary, 
    COUNT(*) AS Count 
FROM desks
UNION ALL
SELECT 
    'Assets Created', 
    COUNT(*) 
FROM assets
UNION ALL
SELECT 
    'Occupied Desks', 
    COUNT(*) 
FROM desks 
WHERE status = 'OCCUPIED'
UNION ALL
SELECT 
    'Empty Desks', 
    COUNT(*) 
FROM desks 
WHERE status = 'EMPTY'
UNION ALL
SELECT 
    'Broken Assets', 
    COUNT(*) 
FROM assets 
WHERE status = 'BROKEN';
